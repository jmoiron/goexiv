#!/usr/bin/perl
# Generates canon_gen.go from the Canon tag tables shipped with exiftool.
#
#   perl internal/gen/canon.pl > canon_gen.go
#
# Each exiv2 Canon group is mapped to an exiftool table; tags are keyed by the
# numeric id that exiv2 reports for them.
use strict;
use warnings;
use Image::ExifTool;
use Image::ExifTool::Canon;

# exiv2 group => exiftool table
my %groups = (
    Canon        => 'Main',
    CanonCs      => 'CameraSettings',
    CanonSi      => 'ShotInfo',
    CanonFi      => 'FileInfo',
    CanonPr      => 'Processing',
    CanonPa      => 'Panorama',
    CanonTi      => 'TimeInfo',
    CanonAfMiAdj => 'AFMicroAdj',
    CanonVigCor2 => 'VignettingCorr2',
    CanonLiOp    => 'LightingOpt',
    CanonLe      => 'LensInfo',
    CanonAm      => 'Ambience',
    CanonMe      => 'MultiExp',
    CanonHdr     => 'HDRInfo',
    CanonAfC     => 'AFConfig',
    CanonRawB    => 'RawBurstInfo',
);

sub q_str { my $s = shift; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return "\"$s\""; }

print "// Code generated by internal/gen/canon.pl from exiftool "
    . $Image::ExifTool::VERSION . "; DO NOT EDIT.\n";
print <<'NOTICE';
//
// The tag names and value conversions in this file are derived from ExifTool,
// Copyright Phil Harvey (https://exiftool.org), which is distributed under the
// same terms as Perl itself: the Perl Artistic License or the GNU GPL. This
// file is used and distributed under the Artistic License. See NOTICE.

NOTICE
print "package makernotes\n\n";
print "var canonTables = map[string]map[int]Tag{\n";

for my $group (sort keys %groups) {
    no strict 'refs';
    my $table = \%{"Image::ExifTool::Canon::$groups{$group}"};
    unless (%$table) { warn "missing table $groups{$group}\n"; next; }
    print "\t\"$group\": {\n";
    for my $id (sort { $a <=> $b } grep { /^\d+$/ } keys %$table) {
        my $info = $table->{$id};
        $info = (grep { ref $_ eq 'HASH' && defined $_->{Name} } @$info)[0] if ref $info eq 'ARRAY';
        my $name = ref $info eq 'HASH' ? $info->{Name} : $info;
        next unless defined $name and !ref $name;
        my $print = ref $info eq 'HASH' ? $info->{PrintConv} : undef;
        my @pairs;
        if (ref $print eq 'HASH') {
            for my $k (sort { $a <=> $b } grep { /^-?\d+$/ } keys %$print) {
                next if ref $print->{$k};
                push @pairs, "$k: " . q_str($print->{$k});
            }
        }
        my $conv = @pairs ? ", Print: map[int64]string{" . join(", ", @pairs) . "}" : "";
        print "\t\t$id: {Name: " . q_str($name) . "$conv},\n";
    }
    print "\t},\n";
}
print "}\n";
